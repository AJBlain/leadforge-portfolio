//go:embed payload.zip
var assets embed.FS
const product="LeadForge"
const version="1.0.0"
const regKey=`HKCU\Software\Microsoft\Windows\CurrentVersion\Uninstall\LeadForge`
func message(title,text string, flags uintptr) int {
 dll:=syscall.NewLazyDLL("user32.dll"); fn:=dll.NewProc("MessageBoxW")
 a,_:=syscall.UTF16PtrFromString(title);b,_:=syscall.UTF16PtrFromString(text)
 result,_,_:=fn.Call(0,uintptr(unsafe.Pointer(b)),uintptr(unsafe.Pointer(a)),flags)
 return int(result)
}
func installDir() string {
 base:=os.Getenv("LOCALAPPDATA")
 if base==""{ base,_=os.UserHomeDir(); }
 return filepath.Join(base,"Programs",product)
}
func psQuote(s string)string{return "'"+strings.ReplaceAll(s,"'","''")+"'"}
func powershell(script string) error {
 runes:=utf16.Encode([]rune(script));data:=make([]byte,len(runes)*2)
 for i,r:=range runes{data[2*i]=byte(r);data[2*i+1]=byte(r>>8)}
 cmd:=exec.Command("powershell.exe","-NoProfile","-ExecutionPolicy","Bypass","-EncodedCommand",base64.StdEncoding.EncodeToString(data))
 cmd.SysProcAttr=&syscall.SysProcAttr{HideWindow:true}
 output,err:=cmd.CombinedOutput();if err!=nil{return fmt.Errorf("%v: %s",err,strings.TrimSpace(string(output)))}
 return nil
}
func shortcuts(root string, remove bool) error {
 exe:=filepath.Join(root,"LeadForge.exe")
 icon:=filepath.Join(root,"LeadForge.ico")
 action:=""; if remove { action=`$s=New-Object -ComObject WScript.Shell; foreach($p in @([Environment]::GetFolderPath('DesktopDirectory'), [Environment]::GetFolderPath('Programs'))) { $f=Join-Path $p 'LeadForge.lnk'; if(Test-Path -LiteralPath $f){ Remove-Item -LiteralPath $f -Force } }` } else {
 action=fmt.Sprintf(`$s=New-Object -ComObject WScript.Shell; foreach($p in @([Environment]::GetFolderPath('DesktopDirectory'), [Environment]::GetFolderPath('Programs'))) { if(-not(Test-Path -LiteralPath $p)){New-Item -ItemType Directory -Force -Path $p | Out-Null};$f=Join-Path $p 'LeadForge.lnk';$c=$s.CreateShortcut($f);$c.TargetPath=%s;$c.WorkingDirectory=%s;$c.IconLocation=%s;$c.Description='LeadForge Property Intelligence Workbench';$c.Save() }`,psQuote(exe),psQuote(root),psQuote(icon+",0"))
 }
 return powershell(action)
}
func registry(root string,remove bool)error{
 if remove{return exec.Command("reg.exe","delete",regKey,"/f").Run()}
 items:=[][2]string{
 {"DisplayName","LeadForge - Property Intelligence Workbench"},
 {"DisplayVersion",version},
 {"Publisher","LeadForge Project"},
 {"InstallLocation",root},
 {"DisplayIcon",filepath.Join(root,"LeadForge.ico")},
 {"UninstallString",`"`+filepath.Join(root,"Uninstall LeadForge.exe")+`" /uninstall`},
 {"QuietUninstallString",`"`+filepath.Join(root,"Uninstall LeadForge.exe")+`" /uninstall /quiet`},
 {"NoModify","1"},
 }
 for _,it:=range items{
  typ:="REG_SZ";if it[0]=="NoModify"{typ="REG_DWORD"}
  out,err:=exec.Command("reg.exe","add",regKey,"/v",it[0],"/t",typ,"/d",it[1],"/f").CombinedOutput()
  if err!=nil{return fmt.Errorf("registry %s: %v: %s",it[0],err,string(out))}
 }
 return nil
}
func extract(root string)error{
 buf,err:=assets.ReadFile("payload.zip");if err!=nil{return err}
 zr,err:=zip.NewReader(bytes.NewReader(buf),int64(len(buf)));if err!=nil{return err}
 for _,entry:=range zr.File{
  // Payload is flat and generated by the release script; never allow path traversal.
  name:=filepath.Clean(entry.Name)
  if name=="."||filepath.IsAbs(name)||strings.Contains(name,"..")||strings.ContainsAny(name,`/\`){return fmt.Errorf("invalid payload path %s",name)}
  if entry.FileInfo().IsDir(){continue}
  in,err:=entry.Open();if err!=nil{return err}
  out,err:=os.OpenFile(filepath.Join(root,name),os.O_CREATE|os.O_TRUNC|os.O_WRONLY,0644)
  if err!=nil{in.Close();return err}
  _,e:=io.Copy(out,in);c:=out.Close();in.Close()
  if e!=nil{return e};if c!=nil{return c}
 }
 return nil
}
func uninstall(quiet bool){
 root:=installDir()
 if !quiet && message(product,"Uninstall LeadForge from this Windows account? Your leads remain stored in your browser profile.",0x01|0x20)!=1{return}
 _=shortcuts(root,true)
 _=registry(root,true)
 // The running uninstaller cannot delete itself. Remove other files now and schedule final folder removal.
 items,_:=os.ReadDir(root)
 for _,it:=range items{if !strings.EqualFold(it.Name(),"Uninstall LeadForge.exe"){_ = os.RemoveAll(filepath.Join(root,it.Name()))}}
 cleanup:=fmt.Sprintf(`ping -n 3 127.0.0.1 >NUL & rmdir /S /Q "%s"`,root)
 cmd:=exec.Command("cmd.exe","/C",cleanup);cmd.SysProcAttr=&syscall.SysProcAttr{HideWindow:true};_ = cmd.Start()
 if !quiet{message(product,"LeadForge has been uninstalled. Existing browser data was preserved.",0x40)}
}
func main(){
 args:=strings.ToLower(strings.Join(os.Args[1:]," "))
 if strings.Contains(args,"/uninstall"){uninstall(strings.Contains(args,"/quiet"));return}
 if message(product+" Setup", "Install LeadForge v"+version+" for the current Windows account?\n\n- No administrator privileges required\n- Creates Desktop and Start Menu shortcuts\n- Installs to Local AppData\n- Keeps existing browser-based lead data",0x01|0x40)!=1{return}
 root:=installDir()
 if err:=os.MkdirAll(root,0755);err!=nil{message(product+" Setup",err.Error(),0x10);return}
 if err:=extract(root);err!=nil{message(product+" Setup","Installation failed: "+err.Error(),0x10);return}
 current,err:=os.Executable();if err!=nil{message(product+" Setup",err.Error(),0x10);return}
 exeData,err:=os.ReadFile(current);if err!=nil{message(product+" Setup",err.Error(),0x10);return}
 if err:=os.WriteFile(filepath.Join(root,"Uninstall LeadForge.exe"),exeData,0644);err!=nil{message(product+" Setup",err.Error(),0x10);return}
 var problems []string
 if err:=shortcuts(root,false);err!=nil{problems=append(problems,"Shortcuts: "+err.Error())}
 if err:=registry(root,false);err!=nil{problems=append(problems,"Add/Remove Programs registration: "+err.Error())}
 if len(problems)>0 {message(product+" Setup","Installed to "+root+" but some integration steps failed:\n"+strings.Join(problems,"\n"),0x30);return}
 if message(product+" Setup","LeadForge v"+version+" installed successfully.\n\nLaunch LeadForge now?",0x04|0x40)==6{
  cmd:=exec.Command(filepath.Join(root,"LeadForge.exe"));cmd.Dir=root;_ = cmd.Start()
 }
}
